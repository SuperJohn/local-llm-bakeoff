"""Generate RESULTS.md from result JSONs. Usage: python -m bakeoff.tables results/legacy results/runs"""
import glob, json, pathlib, sys
from .scoring import summarize


def rows(dirs):
    for d in dirs:
        for f in sorted(glob.glob(f"{d}/*.json")):
            r = json.load(open(f))
            yield r.get("model") or pathlib.Path(f).stem.replace("_", ":", 1), d, r


def render(dirs):
    L = ["# Results", "", "Generated by `make tables`. Hardware: Mac Studio M3 Ultra, 256 GB unified memory.", ""]
    for d in dirs:
        R = [(m, summarize(r)) for m, dd, r in rows([d])]
        if not R: continue
        L += [f"## {d}", "", "### Vision (JSON captions) and voice (streaming)", "",
              "| model | vision JSON valid | vision median s/img | voice TTFT median s | voice tok/s median |",
              "|---|---|---|---|---|"]
        for m, s in R:
            L.append(f"| {m} | {str(s.get('vision_valid_pct', '-')) + '%' if 'vision_valid_pct' in s else '-'} | "
                     f"{s.get('vision_med_s', '-')} | {s.get('voice_ttft_med_s', '-')} | {s.get('voice_tps_med', '-')} |")
        L += ["", "### Agentic tool use", "", "| model | think | tool selected | args correct | task complete | valid JSON |", "|---|---|---|---|---|---|"]
        for m, s in R:
            ag = [(k[6:], v) for k, v in s.items() if k.startswith("agent_")]
            if not ag: L.append(f"| {m} | - | n/a (no tool support) | | | |")
            for lvl, v in ag:
                L.append(f"| {m} | {lvl} | {v['sel']} | {v['args']} | {v['complete']} | {v['json_ok']} |")
        L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    dirs = sys.argv[1:] or ["results/legacy", "results/runs"]
    pathlib.Path("RESULTS.md").write_text(render([d for d in dirs if pathlib.Path(d).exists()]))
    print("wrote RESULTS.md")
